/** 由 ISO 兩碼算出國旗 emoji。 */
export function flagOf(iso) {
  return String.fromCodePoint(
    ...iso
      .toUpperCase()
      .split('')
      .map((c) => 0x1f1e6 + c.charCodeAt(0) - 65)
  )
}
